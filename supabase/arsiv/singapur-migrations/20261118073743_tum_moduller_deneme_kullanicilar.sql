-- Embedra CRM · tüm modüllerin şeması (1/7): CRM ekibi
-- Kurallar: Türkçe tablo adları, tablo başına kısa sütun öneki, bigint identity id, FK'lerde index,
-- sabit listeler için check constraint, created_at. Belge numaraları (S-26-1184, TKL-2026-0001…) ayrı "no" sütununda unique.

create table public.kullanicilar (
  id         bigint generated by default as identity primary key,   -- uygulamada "u" || id ("u2")
  auth_id    uuid unique references auth.users (id) on delete set null,  -- Supabase Auth hesabı (e-posta onaylanınca bağlanır)
  k_ad       text not null check (length(trim(k_ad)) > 0),
  k_eposta   text not null,
  k_rol      text not null check (k_rol in ('Yönetici', 'Satış', 'Destek', 'Operasyon', 'Pazarlama')),
  k_aktif    boolean not null default true,
  k_tel      text,
  created_at timestamptz not null default now()
);
comment on table public.kullanicilar is 'CRM ekibi (Operasyon › Ekip)';
create unique index kullanicilar_eposta_key on public.kullanicilar (lower(k_eposta));
alter table public.kullanicilar enable row level security;
