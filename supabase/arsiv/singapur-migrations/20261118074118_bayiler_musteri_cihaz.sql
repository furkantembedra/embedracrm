-- Embedra CRM · tüm modüllerin şeması (4/7): bayiler, müşteri yetkilileri / izinleri, cihaz alanları
-- Kurallar: Türkçe tablo adları, tablo başına kısa sütun öneki, bigint identity id, FK'lerde index,
-- sabit listeler için check constraint, created_at. Belge numaraları (S-26-1184, TKL-2026-0001…) ayrı "no" sütununda unique.

-- ═════════════════════════════════════════════════════════════
-- 2. Bayiler (aktif bayi kartı) — diğer tablolar buna bağlanır
-- ═════════════════════════════════════════════════════════════
-- Başvurudan lansmana geçen bayinin id'si başvurunun id'siyle aynıdır (uygulama bu eşitliğe dayanır);
-- başvurusu olmayan bayi aynı diziden yeni id alır, böylece iki tabloda id çakışmaz.
create table public.bayiler (
  id                bigint primary key default nextval(pg_get_serial_sequence('public.bayi_basvurulari', 'id')),
  basvuru_id        bigint unique references public.bayi_basvurulari (id) on delete set null,
  by_ad             text not null check (length(trim(by_ad)) > 0),
  by_bolge          text,
  by_ulke_kodu      text not null,
  by_moq_hedef      integer not null default 0 check (by_moq_hedef >= 0),   -- çeyreklik minimum sipariş (cihaz)
  temsilci_id       bigint references public.kullanicilar (id) on delete set null,
  by_adres          text,
  by_sozlesme_bat   date,
  by_sozlesme_sure_ay smallint check (by_sozlesme_sure_ay is null or by_sozlesme_sure_ay > 0),
  created_at        timestamptz not null default now(),
  constraint bayiler_basvuru_ayni_id check (basvuru_id is null or basvuru_id = id)
);
comment on table public.bayiler is 'Aktif bayiler. Stok / satış / MOQ sayaçları bayi_hareketleri''nden hesaplanır.';
create index bayiler_temsilci_id_idx on public.bayiler (temsilci_id);

-- Bayi portalı hesapları (Supabase Auth). Hesap e-postası onaylanınca auth_id bağlanır.
create table public.bayi_kullanicilari (
  id           bigint generated by default as identity primary key,
  bayi_id      bigint not null references public.bayiler (id) on delete cascade,
  auth_id      uuid unique references auth.users (id) on delete set null,
  bk_eposta    text not null,
  bk_erisim    boolean not null default false,
  bk_son_giris timestamptz,
  created_at   timestamptz not null default now()
);
comment on table public.bayi_kullanicilari is 'Bayi portalı hesapları';
create unique index bayi_kullanicilari_eposta_key on public.bayi_kullanicilari (lower(bk_eposta));
create index bayi_kullanicilari_bayi_id_idx on public.bayi_kullanicilari (bayi_id);

