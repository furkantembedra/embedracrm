-- 3.2 musteri: tek yetkili alanları musteri_yetkilileri tablosuna taşınır
alter table public.musteri
  add column m_toplam_deger numeric(14, 2) check (m_toplam_deger is null or m_toplam_deger >= 0),  -- TL
  add column m_son_temas    date;
comment on column public.musteri.m_dk is 'Kullanılmıyor: izinler iletisim_izinleri tablosunda yetkili + kanal bazında';

create table public.musteri_yetkilileri (
  id         bigint generated by default as identity primary key,
  musteri_id bigint not null references public.musteri (id) on delete cascade,
  y_ad       text not null,
  y_unvan    text not null default '',
  y_tel      text not null default '',
  y_eposta   text not null default '',
  y_sira     smallint not null default 0,   -- 0: birincil yetkili
  created_at timestamptz not null default now()
);
comment on table public.musteri_yetkilileri is 'Müşteri iletişim kişileri (ilk sıradaki birincil)';
create index musteri_yetkilileri_musteri_idx on public.musteri_yetkilileri (musteri_id, y_sira);
create index musteri_yetkilileri_tel_idx on public.musteri_yetkilileri (y_tel);

create table public.iletisim_izinleri (
  id         bigint generated by default as identity primary key,
  yetkili_id bigint not null references public.musteri_yetkilileri (id) on delete cascade,
  i_kanal    text not null check (i_kanal in ('eposta', 'whatsapp', 'sms', 'arama')),
  i_verildi  boolean not null,
  i_tarih    date not null,
  i_kaynak   text not null,
  i_cekilme  date,
  created_at timestamptz not null default now(),
  constraint iletisim_izinleri_yetkili_kanal_key unique (yetkili_id, i_kanal)
);
comment on table public.iletisim_izinleri is 'Ticari ileti izinleri (kayıt silinmez, geri çekilme tarihiyle kanıt olarak kalır)';

alter table public.musteri_olaylari add column o_kaynak text;   -- "Satış hattı", "WhatsApp", "RMA"…

-- 3.3 cihazlar
alter table public.cihazlar
  add column c_sahip_adi   text,                                    -- müşteri kaydı yoksa son kullanıcı / bayi adı
  add column c_ulke        text,
  add column plan_id       bigint references public.lisans_planlari (id),   -- güncel lisans (geçmiş: lisanslar)
  add column c_lisans_bat  date,
  add column c_lisans_bit  date,
  add column c_son_gorulme timestamptz,                             -- ONESuite'in son bildirimi
  add column bayi_id       bigint references public.bayiler (id) on delete set null,
  add column c_stoga_giris date;                                    -- bayiye sevk tarihi
alter table public.cihazlar add constraint cihazlar_lisans_tarih_check check (c_lisans_bit is null or c_lisans_bat is null or c_lisans_bit > c_lisans_bat);
create index cihazlar_bayi_id_idx on public.cihazlar (bayi_id);
create index cihazlar_plan_id_idx on public.cihazlar (plan_id);
create index cihazlar_son_gorulme_idx on public.cihazlar (c_son_gorulme);
comment on column public.cihazlar.plan_id is 'Güncel lisans planı; lisans geçmişi lisanslar tablosunda';

create table public.cihaz_surum_gecmisi (
  id         bigint generated always as identity primary key,
  cihaz_id   bigint not null references public.cihazlar (id) on delete cascade,
  sg_eski    text not null,
  sg_yeni    text not null,
  sg_kaynak  text not null check (sg_kaynak in ('cihaz', 'elle')),
  created_at timestamptz not null default now()
);
comment on table public.cihaz_surum_gecmisi is 'Firmware sürüm değişiklikleri';
create index cihaz_surum_gecmisi_cihaz_zaman_idx on public.cihaz_surum_gecmisi (cihaz_id, created_at desc);

create table public.garanti_uzatmalari (
  id         bigint generated by default as identity primary key,
  cihaz_id   bigint not null references public.cihazlar (id) on delete cascade,
  gu_ay      smallint not null check (gu_ay in (6, 12, 24, 36)),
  gu_tarih   date not null,
  gu_not     text not null default '',
  created_at timestamptz not null default now()
);
create index garanti_uzatmalari_cihaz_id_idx on public.garanti_uzatmalari (cihaz_id);

