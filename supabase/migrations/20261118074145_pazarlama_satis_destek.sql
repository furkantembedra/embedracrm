-- Embedra CRM · tüm modüllerin şeması (5/7): pazarlama, satış hattı, WhatsApp, destek
-- Kurallar: Türkçe tablo adları, tablo başına kısa sütun öneki, bigint identity id, FK'lerde index,
-- sabit listeler için check constraint, created_at. Belge numaraları (S-26-1184, TKL-2026-0001…) ayrı "no" sütununda unique.

-- ═════════════════════════════════════════════════════════════
-- 4. Pazarlama (satış hattı kampanyaya bağlandığı için önce)
-- ═════════════════════════════════════════════════════════════
create table public.kampanyalar (
  id                  bigint generated by default as identity primary key,
  kp_ad               text not null check (length(trim(kp_ad)) > 0),
  kp_kanal            text not null check (kp_kanal in ('E-posta', 'Instagram', 'WhatsApp', 'Fuar')),
  kp_liste            text not null,   -- hazır liste kodu (bitiyor, basic…) ya da ozel_listeler.id
  kp_baslangic        date not null,
  kp_bitis            date,
  kp_durum            text not null default 'Taslak' check (kp_durum in ('Taslak', 'Aktif', 'Tamamlandı')),
  kp_not              text not null default '',
  kp_mesaj_konu       text,
  kp_mesaj_metin      text,
  kp_mesaj_sablon     text,
  kp_otomasyon_tur    text not null default 'yok' check (kp_otomasyon_tur in ('yok', 'planli', 'surekli')),
  kp_otomasyon_zaman  timestamp,   -- yerel saat
  created_at          timestamptz not null default now(),
  constraint kampanyalar_tarih_check check (kp_bitis is null or kp_bitis >= kp_baslangic)
);

create table public.medya_dosyalari (
  id         uuid primary key default gen_random_uuid(),   -- Storage yolu: pazarlama-medya/<id>
  md_ad      text not null,
  md_tip     text not null,
  md_boyut   bigint not null check (md_boyut >= 0),
  created_at timestamptz not null default now()
);
comment on table public.medya_dosyalari is 'İçerik görselleri / videoları (dosya: Storage pazarlama-medya bucket)';

create table public.icerikler (
  id            bigint generated by default as identity primary key,
  ic_tarih      date not null,
  ic_kanal      text not null check (ic_kanal in ('Instagram', 'Bülten / e-posta', 'Blog', 'WhatsApp', 'LinkedIn')),
  ic_baslik     text not null check (length(trim(ic_baslik)) > 0),
  ic_paylasildi boolean not null default false,
  kampanya_id   bigint references public.kampanyalar (id) on delete set null,
  ic_aciklama   text not null default '',
  ic_hashtaglar text[] not null default '{}',
  ic_bayi_paylas boolean not null default false,
  created_at    timestamptz not null default now()
);
create index icerikler_kampanya_id_idx on public.icerikler (kampanya_id);
create index icerikler_tarih_idx on public.icerikler (ic_tarih);

create table public.icerik_medyalari (
  icerik_id bigint not null references public.icerikler (id) on delete cascade,
  medya_id  uuid not null references public.medya_dosyalari (id) on delete cascade,
  im_sira   smallint not null default 0,
  primary key (icerik_id, medya_id)
);
create index icerik_medyalari_medya_id_idx on public.icerik_medyalari (medya_id);

create table public.kampanya_gonderimleri (
  id          bigint generated by default as identity primary key,
  kampanya_id bigint not null references public.kampanyalar (id) on delete cascade,
  kg_kanal    text not null check (kg_kanal in ('eposta', 'whatsapp')),
  kg_zaman    timestamp not null,
  kg_tur      text not null check (kg_tur in ('elle', 'planli', 'otomatik', 'test')),
  kg_alici    integer not null default 0 check (kg_alici >= 0),
  kg_basarili integer not null default 0 check (kg_basarili >= 0),
  kg_hatali   integer not null default 0 check (kg_hatali >= 0),
  kg_atlanan  integer not null default 0 check (kg_atlanan >= 0),
  kg_demo     boolean not null default false,
  kg_hatalar  text[] not null default '{}',
  created_at  timestamptz not null default now()
);
create index kampanya_gonderimleri_kampanya_idx on public.kampanya_gonderimleri (kampanya_id, kg_zaman desc);

-- Kampanyanın ulaştığı kişiler (e-posta ya da telefon); aynı kişiye ikinci kez gönderilmez
create table public.kampanya_ulasilanlar (
  kampanya_id bigint not null references public.kampanyalar (id) on delete cascade,
  anahtar     text not null,
  created_at  timestamptz not null default now(),
  primary key (kampanya_id, anahtar)
);

-- Abonelikten çıkan e-posta / telefonlar
create table public.abonelik_engelleri (
  anahtar    text primary key,
  created_at timestamptz not null default now()
);

create table public.ozel_listeler (
  id                      bigint generated by default as identity primary key,
  ol_ad                   text not null check (length(trim(ol_ad)) > 0),
  ol_filtre               jsonb not null default '{}'::jsonb,   -- {segment, plan, ulke, izin}
  ol_aktarim_kaynak       text,    -- doluysa dosyadan içe aktarılmış liste
  ol_aktarim_tarih        date,
  ol_aktarim_izin_kaynagi text,
  created_at              timestamptz not null default now()
);

create table public.liste_kisileri (
  id          bigint generated by default as identity primary key,
  liste_id    bigint not null references public.ozel_listeler (id) on delete cascade,
  lk_firma    text not null default '',
  lk_kisi     text not null default '',
  lk_eposta   text not null default '',
  lk_telefon  text not null default '',
  lk_ulke     text not null default '',
  lk_kanallar text[] not null default '{}',
  lk_sira     integer not null default 0
);
create index liste_kisileri_liste_idx on public.liste_kisileri (liste_id, lk_sira);

