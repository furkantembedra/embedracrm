alter table public.satis_hatti
  add column f_kayip_nedeni   text check (f_kayip_nedeni in ('Fiyat yüksek bulundu', 'Rakibi seçti', 'Bütçe yok', 'Yanıt vermiyor', 'İhtiyacı kalmadı', 'Diğer')),
  add column f_kayip_aciklama text,
  add column kampanya_id      bigint references public.kampanyalar (id) on delete set null,
  add column f_telefon        text,                           -- "+905321234567"
  add column f_son_hareket    date not null default current_date,
  add column f_sira           integer not null default 0,     -- kanban sütunundaki sıra
  add column f_kazanc_islendi boolean not null default false; -- kazanılınca müşteri / sipariş bir kez açılır
create index satis_hatti_kampanya_id_idx on public.satis_hatti (kampanya_id);
create index satis_hatti_telefon_idx on public.satis_hatti (f_telefon);

create table public.whatsapp_mesajlari (
  id             bigint generated always as identity primary key,
  satis_hatti_id bigint not null references public.satis_hatti (id) on delete cascade,
  w_mesaj_id     text not null unique,   -- Meta wamid (aynı mesaj iki kez işlenmez); CRM notunda uuid
  w_metin        text not null,
  w_yon          text not null check (w_yon in ('gelen', 'giden')),
  w_tur          text not null default 'text',
  w_zaman        timestamptz not null,
  created_at     timestamptz not null default now()
);
create index whatsapp_mesajlari_firsat_zaman_idx on public.whatsapp_mesajlari (satis_hatti_id, w_zaman);

