create table public.bilesenler (
  id         bigint generated by default as identity primary key,
  bs_kod     text not null unique,   -- "PCB-MAIN"
  bs_ad      text not null,
  bs_adet    integer not null default 0 check (bs_adet >= 0),
  bs_kritik  integer not null default 0 check (bs_kritik >= 0),
  bs_hedef   integer not null default 0 check (bs_hedef >= 0),
  bs_kaynak  text not null default 'dis' check (bs_kaynak in ('dis', 'ic')),   -- dış tedarik / atölyede iç üretim
  created_at timestamptz not null default now()
);

create table public.urun_receteleri (
  ur_model   text not null check (ur_model in ('ONE', 'ONE Lite')),
  bilesen_id bigint not null references public.bilesenler (id) on delete cascade,
  ur_sira    smallint not null default 0,
  primary key (ur_model, bilesen_id)
);
create index urun_receteleri_bilesen_id_idx on public.urun_receteleri (bilesen_id);

create table public.ic_uretim_emirleri (
  id           bigint generated by default as identity primary key,
