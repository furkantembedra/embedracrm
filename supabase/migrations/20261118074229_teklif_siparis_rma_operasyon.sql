  up_not         text not null default '',
  up_tamirde     integer check (up_tamirde is null or up_tamirde >= 0),
  up_onarilan    integer check (up_onarilan is null or up_onarilan >= 0),
  up_sokulen     integer check (up_sokulen is null or up_sokulen >= 0),
  up_hurda       integer check (up_hurda is null or up_hurda >= 0),
  up_geri_alinan jsonb,   -- sökülen cihazlardan bileşen stoğuna dönen parçalar {"PCB-MAIN": 1}
  created_at     timestamptz not null default now()
);

create table public.tedarik_siparisleri (
  id           bigint generated by default as identity primary key,
  ts_no        text not null unique,   -- "T-0031"
  ts_tedarikci text not null,
  ts_kalem_kodu text not null,         -- bileşen kodu ya da sipariş deposu kodu (EO1-CBL-…)
  ts_kalem_adi text not null,
  ts_adet      integer not null check (ts_adet > 0),
  ts_tarih     date not null,
  ts_beklenen  date not null,
  ts_durum     text not null default 'siparis' check (ts_durum in ('siparis', 'yolda', 'teslim')),
  created_at   timestamptz not null default now()
);

-- Üretilmiş, depoda bekleyen, henüz siparişe atanmamış seri numaraları
create table public.seri_havuzu (
  sh_seri_no text primary key,
  sh_model   text not null check (sh_model in ('ONE', 'ONE Lite')),
  sh_parti_no text not null,   -- uretim_partileri.up_no ya da "iptal" (iptal edilen siparişten dönen)
  sh_sira    bigint generated always as identity,
  created_at timestamptz not null default now()
);
