  iug_tarih    date not null,
  iug_adet     integer not null check (iug_adet > 0),
  iug_personel text not null,
  iug_not      text not null default '',
  created_at   timestamptz not null default now()
);
create index ic_uretim_girisleri_emir_idx on public.ic_uretim_girisleri (emir_id, iug_tarih);

create table public.uretim_partileri (
  id             bigint generated by default as identity primary key,
  up_no          text not null unique,   -- "P-2611-01"
  up_model       text not null check (up_model in ('ONE', 'ONE Lite')),
  up_adet        integer not null check (up_adet > 0),
  up_hedef_tarih date not null,
