-- Embedra CRM · tüm modüllerin şeması (6/7): teklif, sipariş, stok, iade, RMA, operasyon
-- Kurallar: Türkçe tablo adları, tablo başına kısa sütun öneki, bigint identity id, FK'lerde index,
-- sabit listeler için check constraint, created_at. Belge numaraları (S-26-1184, TKL-2026-0001…) ayrı "no" sütununda unique.

-- ═════════════════════════════════════════════════════════════
-- 7. Teklifler
-- ═════════════════════════════════════════════════════════════
create table public.teklifler (
  id                 bigint generated by default as identity primary key,
  tk_no              text not null unique,          -- "TKL-2026-0001", revizyonda "TKL-2026-0001-v2"
  tk_gorunen_no      text not null,                 -- "TKL-2026-0001 v2"
  tk_kok             text not null,                 -- ilk sürümün tk_no'su
  tk_versiyon        smallint not null default 1 check (tk_versiyon > 0),
  satis_hatti_id     bigint references public.satis_hatti (id) on delete set null,
  tk_firma           text not null,
  tk_konum           text not null default '',
  tk_iskonto         numeric(5, 2) not null default 0 check (tk_iskonto between 0 and 100),
  tk_kdv             numeric(4, 3) not null default 0.2 check (tk_kdv between 0 and 1),
  tk_gecerlilik      date not null,
  tk_odeme_sartlari  text not null default '',
  tk_teslim_sartlari text not null default '',
  tk_not             text not null default '',
  tk_durum           text not null default 'taslak' check (tk_durum in ('taslak', 'gonderildi', 'kabul', 'red', 'revize')),
  tk_olusturma       date not null default current_date,
  tk_gonderim        date,
  tk_sonuc           date,
  tk_siparis_no      text,                          -- kabulde açılan sipariş
  created_at         timestamptz not null default now(),
  constraint teklifler_kok_versiyon_key unique (tk_kok, tk_versiyon)
);
create index teklifler_satis_hatti_id_idx on public.teklifler (satis_hatti_id);

create table public.teklif_kalemleri (
  id          bigint generated by default as identity primary key,
  teklif_id   bigint not null references public.teklifler (id) on delete cascade,
  tkk_sira    smallint not null default 0,
  tkk_tur     text not null check (tkk_tur in ('cihaz', 'lisans', 'ozel')),
  tkk_model   text check (tkk_model in ('ONE', 'ONE Lite')),
  tkk_paket   text,
  tkk_aciklama text,
  tkk_adet    integer not null check (tkk_adet > 0),
  tkk_birim_fiyat numeric(14, 2) not null,   -- özel kalemde negatif olabilir (mahsup)
  tkk_kdvli   boolean not null default true,
  constraint teklif_kalemleri_tur_check check (
    (tkk_tur = 'cihaz' and tkk_model is not null) or (tkk_tur = 'lisans' and tkk_paket is not null) or (tkk_tur = 'ozel' and tkk_aciklama is not null))
);
create index teklif_kalemleri_teklif_idx on public.teklif_kalemleri (teklif_id, tkk_sira);

-- ═════════════════════════════════════════════════════════════
-- 8. Sipariş, stok, iade
-- ═════════════════════════════════════════════════════════════
create table public.siparisler (
  id                    bigint generated by default as identity primary key,
  sp_no                 text not null unique,           -- "S-26-1184"
  sp_tarih              timestamp not null,             -- yerel saat
  musteri_id            bigint references public.musteri (id) on delete set null,
  bayi_id               bigint references public.bayiler (id) on delete set null,
  sp_musteri_adi        text not null,
  sp_ulke               text not null default '',
  sp_adres              text not null default '',
  teklif_id             bigint references public.teklifler (id) on delete set null,
  sp_tutar              numeric(14, 2) not null check (sp_tutar >= 0),   -- KDV hariç
  sp_para_birimi        text not null default 'TRY' check (sp_para_birimi in ('TRY', 'EUR')),
  sp_odeme              text not null check (sp_odeme in ('Kart', 'Havale/EFT', 'Proforma')),
  sp_durum              text not null default 'odeme' check (sp_durum in ('odeme', 'hazirlaniyor', 'kargoda', 'teslim', 'tamamlandi', 'iptal')),
  sp_seri_nolar         text[] not null default '{}',   -- atanan cihaz seri numaraları
  sp_kargo_firma        text,
  sp_kargo_takip        text,
  sp_teslim_tarihi      date,
  sp_fatura_no          text,
  sp_lisans_bat         date,
  sp_iptal_tarihi       date,
  sp_iptal_neden        text,
  sp_iptal_kim          text check (sp_iptal_kim in ('embedra', 'bayi')),
  sp_iptal_odeme_iadesi boolean,
  created_at            timestamptz not null default now(),
  constraint siparisler_iptal_check check (sp_durum <> 'iptal' or (sp_iptal_tarihi is not null and sp_iptal_kim is not null))
);
create index siparisler_musteri_id_idx on public.siparisler (musteri_id);
create index siparisler_bayi_id_idx on public.siparisler (bayi_id);
create index siparisler_teklif_id_idx on public.siparisler (teklif_id);
create index siparisler_tarih_idx on public.siparisler (sp_tarih desc);

create table public.siparis_kalemleri (
  id          bigint generated by default as identity primary key,
  siparis_id  bigint not null references public.siparisler (id) on delete cascade,
  sk_sira     smallint not null default 0,
  sk_tur      text not null check (sk_tur in ('cihaz', 'lisans', 'aksesuar')),
  sk_model    text check (sk_model in ('ONE', 'ONE Lite')),
  sk_paket    text,
  sk_sure_ay  smallint check (sk_sure_ay is null or sk_sure_ay > 0),
  sk_stok_kodu text,
  sk_adet     integer not null check (sk_adet > 0),
  constraint siparis_kalemleri_tur_check check (
    (sk_tur = 'cihaz' and sk_model is not null) or (sk_tur = 'lisans' and sk_paket is not null and sk_sure_ay is not null) or (sk_tur = 'aksesuar' and sk_stok_kodu is not null))
);
create index siparis_kalemleri_siparis_idx on public.siparis_kalemleri (siparis_id, sk_sira);

-- Bayi lisans siparişinde lisansların gideceği cihazlar
create table public.siparis_lisans_atamalari (
  id          bigint generated by default as identity primary key,
  siparis_id  bigint not null references public.siparisler (id) on delete cascade,
  sla_seri_no text not null,
  sla_plan    text not null,
  sla_sure_ay smallint not null check (sla_sure_ay > 0)
);
create index siparis_lisans_atamalari_siparis_idx on public.siparis_lisans_atamalari (siparis_id);

create table public.siparis_notlari (
  id         bigint generated by default as identity primary key,
  siparis_id bigint not null references public.siparisler (id) on delete cascade,
  sn_metin   text not null,
  sn_sistem  boolean not null default false,
  sn_zaman   timestamp not null,   -- yerel saat
  created_at timestamptz not null default now()
);
create index siparis_notlari_siparis_zaman_idx on public.siparis_notlari (siparis_id, sn_zaman);

create table public.stok_kalemleri (
  id         bigint generated by default as identity primary key,
  st_kod     text not null unique,   -- "EO1-HW", "EO1-CBL-MAIN"
  st_ad      text not null,
  st_adet    integer not null default 0 check (st_adet >= 0),
  st_kritik  integer not null default 0 check (st_kritik >= 0),
  st_hedef   integer not null default 0 check (st_hedef >= 0),
  st_fiyat   numeric(14, 2) check (st_fiyat is null or st_fiyat >= 0),   -- aksesuar satış fiyatı (cihazlarda null)
  created_at timestamptz not null default now()
);
comment on table public.stok_kalemleri is 'Sipariş deposu: cihazlar ve kablolar';

create table public.iadeler (
  id             bigint generated by default as identity primary key,
  ia_no          text not null unique,     -- "R-0042"
  ia_siparis_no  text not null,            -- eski / silinmiş siparişe de bağlanabildiği için FK değil
  siparis_id     bigint references public.siparisler (id) on delete set null,
  ia_musteri_adi text not null,
  ia_tur         text not null check (ia_tur in ('iade', 'degisim')),
  ia_neden       text not null,
  ia_urunler     text[] not null default '{}',
  ia_tarih       date not null,
  ia_adim        smallint not null default 0 check (ia_adim >= 0),
  created_at     timestamptz not null default now()
);
create index iadeler_siparis_id_idx on public.iadeler (siparis_id);

-- ═════════════════════════════════════════════════════════════
-- 9. Garanti & RMA
-- ═════════════════════════════════════════════════════════════
create table public.rma_kayitlari (
  id                    bigint generated by default as identity primary key,
  r_no                  text not null unique,      -- "RMA-0007"
  r_seri_no             text not null,
  r_model               text not null check (r_model in ('ONE', 'ONE Lite')),
  r_sahip_tur           text not null check (r_sahip_tur in ('musteri', 'bayi')),
  musteri_id            bigint references public.musteri (id) on delete set null,
  bayi_id               bigint references public.bayiler (id) on delete set null,
  r_sahip_adi           text not null,
  r_ariza_tipi          text not null check (r_ariza_tipi in ('Ekran / dokunmatik', 'Bağlantı (OBD / K-Line)', 'Güç / batarya', 'Yazılım / firmware', 'Kablo / aksesuar', 'Fiziksel hasar', 'Diğer')),
  r_ariza               text not null,
  r_fotograflar         text[] not null default '{}',   -- eski kayıtlarda dosya adı / bağlantı
  r_garantide           boolean not null,
  r_garanti_elle        boolean,
  r_ucret               numeric(14, 2) check (r_ucret is null or r_ucret >= 0),
  r_adim                text not null default 'talep' check (r_adim in ('talep', 'teslim_alindi', 'inceleme', 'karar', 'tamamlandi', 'gonderildi')),
  r_karar               text check (r_karar in ('tamir', 'degisim', 'iade', 'red')),
  r_kullanilan_parcalar jsonb not null default '{}'::jsonb,   -- {"PCB-MAIN": 1}
  r_yeni_seri           text,
  destek_talebi_id      bigint references public.destek_talepleri (id) on delete set null,
  r_iade_no             text,
  r_kaynak              text not null default 'crm' check (r_kaynak in ('crm', 'bayi-portali')),
  r_acilis              date not null,
  r_kapanis             date,
  r_gelis_kanal         text check (r_gelis_kanal in ('Kargo', 'Elden teslim', 'Bayi üzerinden', 'Saha servisi')),
  r_gelis_takip         text,
  r_kargo_firma         text,
  r_kargo_takip         text,
  r_ucret_odendi        boolean not null default false,
  r_ucret_onay          boolean not null default false,
  r_oncelik             text not null default 'Normal' check (r_oncelik in ('Normal', 'Acil')),
  created_at            timestamptz not null default now()
);
create index rma_kayitlari_seri_no_idx on public.rma_kayitlari (r_seri_no);
create index rma_kayitlari_yeni_seri_idx on public.rma_kayitlari (r_yeni_seri);
create index rma_kayitlari_musteri_id_idx on public.rma_kayitlari (musteri_id);
create index rma_kayitlari_bayi_id_idx on public.rma_kayitlari (bayi_id);
create index rma_kayitlari_destek_talebi_id_idx on public.rma_kayitlari (destek_talebi_id);

create table public.rma_gecmisi (
  id         bigint generated by default as identity primary key,
  rma_id     bigint not null references public.rma_kayitlari (id) on delete cascade,
  rg_zaman   timestamp not null,
  rg_metin   text not null,
  rg_tur     text check (rg_tur in ('sistem', 'not', 'gorusme')),
  rg_yazan   text
);
create index rma_gecmisi_rma_zaman_idx on public.rma_gecmisi (rma_id, rg_zaman);

create table public.rma_ekleri (
  id         bigint generated by default as identity primary key,
  rma_id     bigint not null references public.rma_kayitlari (id) on delete cascade,
  re_ad      text not null,
  re_tip     text not null,
  re_boyut   bigint not null check (re_boyut >= 0),
  re_yol     text not null,   -- Storage: rma-ekleri/<yol>
  re_tarih   timestamp not null,
  created_at timestamptz not null default now()
);
create index rma_ekleri_rma_id_idx on public.rma_ekleri (rma_id);

