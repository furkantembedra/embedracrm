-- Embedra CRM · tüm modüllerin şeması (7/7): hatırlatma, otomasyon, bayi hareketleri / portal / dokümanlar
-- Kurallar: Türkçe tablo adları, tablo başına kısa sütun öneki, bigint identity id, FK'lerde index,
-- sabit listeler için check constraint, created_at. Belge numaraları (S-26-1184, TKL-2026-0001…) ayrı "no" sütununda unique.

-- ═════════════════════════════════════════════════════════════
-- 11. Hatırlatmalar ve otomasyon
-- ═════════════════════════════════════════════════════════════
create table public.hatirlatmalar (
  id            bigint generated by default as identity primary key,
  h_baslik      text not null check (length(trim(h_baslik)) > 0),
  h_aciklama    text not null default '',
  h_kayit_tur   text check (h_kayit_tur in ('firsat', 'teklif', 'siparis', 'musteri', 'bayi', 'rma', 'stok', 'cihaz', 'destek')),
  h_kayit_id    text,
  h_kayit_ad    text,
  h_kayit_href  text,
  sorumlu_id    bigint not null references public.kullanicilar (id) on delete restrict,
  h_zaman       timestamp not null,   -- yerel saat
  h_durum       text not null default 'bekliyor' check (h_durum in ('bekliyor', 'tamam')),
  h_onem        text not null default 'normal' check (h_onem in ('normal', 'yuksek')),
  h_tamamlanma  timestamp,
  created_at    timestamptz not null default now()
);
comment on table public.hatirlatmalar is 'Elle eklenen hatırlatmalar (otomatikler her okumada kurallardan hesaplanır)';
create index hatirlatmalar_sorumlu_id_idx on public.hatirlatmalar (sorumlu_id);
create index hatirlatmalar_durum_zaman_idx on public.hatirlatmalar (h_durum, h_zaman);

-- Otomatik hatırlatmaların "tamam / ertelendi" durumu ("oto:<kural>:<kayıt>" anahtarıyla)
create table public.hatirlatma_durumlari (
  anahtar      text primary key,
  hd_tamam     timestamp,
  hd_ertelendi timestamp,
  updated_at   timestamptz not null default now()
);

create table public.hatirlatma_okunanlar (
  anahtar    text primary key,
  created_at timestamptz not null default now()
);

create table public.otomasyon_kurallari (
  id                bigint generated by default as identity primary key,
  ok_ad             text not null check (length(trim(ok_ad)) > 0),
  ok_aktif          boolean not null default true,
  ok_tetikleyici    text not null check (ok_tetikleyici in ('lisans-bitiyor', 'teklif-yanitsiz', 'rma-gecikti', 'siparis-kargolanmadi', 'firsat-hareketsiz', 'stok-kritik', 'destek-yanitsiz', 'cihaz-sessiz')),
  ok_gun            integer not null default 0 check (ok_gun >= 0),
  ok_filtre         jsonb not null default '{}'::jsonb,   -- {ulke, plan, model}
  ok_engel          text,
  hatirlatma_sorumlu_id bigint references public.kullanicilar (id) on delete set null,   -- null: hatırlatma eylemi yok
  ok_hatirlatma_onem text check (ok_hatirlatma_onem in ('normal', 'yuksek')),
  ok_eposta_konu    text,   -- null: e-posta eylemi yok
  ok_eposta_metin   text,
  ok_son_calisma    timestamptz,
  created_at        timestamptz not null default now()
);
create index otomasyon_kurallari_sorumlu_idx on public.otomasyon_kurallari (hatirlatma_sorumlu_id);

create table public.otomasyon_calismalari (
  id          bigint generated by default as identity primary key,
  kural_id    bigint references public.otomasyon_kurallari (id) on delete set null,
  oc_kural_ad text not null,
  oc_kayit_ad text not null,
  oc_href     text not null,
  oc_sonuclar jsonb not null default '[]'::jsonb,   -- [{eylem, durum, ayrinti}]
  oc_zaman    timestamptz not null default now()
);
create index otomasyon_calismalari_zaman_idx on public.otomasyon_calismalari (oc_zaman desc);
create index otomasyon_calismalari_kural_id_idx on public.otomasyon_calismalari (kural_id);

-- Bir kuralın aynı kayıt için ikinci kez çalışmasını önler
create table public.otomasyon_islenenler (
  kural_id   bigint not null references public.otomasyon_kurallari (id) on delete cascade,
  anahtar    text not null,
  created_at timestamptz not null default now(),
  primary key (kural_id, anahtar)
);

-- ═════════════════════════════════════════════════════════════
-- 12. Bayi hareketleri, lisans havuzu, portal talepleri
-- ═════════════════════════════════════════════════════════════
create table public.bayi_hareketleri (
  id             bigint generated by default as identity primary key,
  bayi_id        bigint not null references public.bayiler (id) on delete cascade,
  bh_tur         text not null check (bh_tur in ('sevkiyat', 'satis', 'lisans', 'iade', 'degisim')),
  bh_tarih       date not null,
  musteri_id     bigint references public.musteri (id) on delete set null,
  bh_musteri_adi text,
  bh_plan        text check (bh_plan in ('Basic', 'Pro', 'Pro+')),
  bh_sure_ay     smallint check (bh_sure_ay is null or bh_sure_ay > 0),
  bh_eski_seri   text,
  bh_not         text,
  created_at     timestamptz not null default now()
);
create index bayi_hareketleri_bayi_tarih_idx on public.bayi_hareketleri (bayi_id, bh_tarih desc);
create index bayi_hareketleri_musteri_id_idx on public.bayi_hareketleri (musteri_id);

create table public.bayi_hareket_kalemleri (
  id          bigint generated by default as identity primary key,
  hareket_id  bigint not null references public.bayi_hareketleri (id) on delete cascade,
  bhk_model   text not null check (bhk_model in ('ONE', 'ONE Lite')),
  bhk_seri_no text,   -- seri no girilmeden sevk edilen stokta null
  bhk_sira    integer not null default 0
);
create index bayi_hareket_kalemleri_hareket_idx on public.bayi_hareket_kalemleri (hareket_id, bhk_sira);
create index bayi_hareket_kalemleri_seri_idx on public.bayi_hareket_kalemleri (bhk_seri_no);

create table public.bayi_lisans_havuzu (
  id          bigint generated by default as identity primary key,
  bayi_id     bigint not null references public.bayiler (id) on delete cascade,
  blh_paket   text not null check (blh_paket in ('Basic', 'Pro', 'Pro+')),
  blh_sure_ay smallint not null check (blh_sure_ay > 0),
  blh_adet    integer not null check (blh_adet >= 0),
  blh_kaynak  text not null,   -- sipariş no
  blh_tarih   date not null,
  created_at  timestamptz not null default now()
);
create index bayi_lisans_havuzu_bayi_idx on public.bayi_lisans_havuzu (bayi_id, blh_paket, blh_tarih);

create table public.bayi_yenileme_talepleri (
  byt_seri_no text primary key,
  bayi_id     bigint not null references public.bayiler (id) on delete cascade,
  byt_tarih   date not null,
  created_at  timestamptz not null default now()
);
create index bayi_yenileme_talepleri_bayi_id_idx on public.bayi_yenileme_talepleri (bayi_id);

create table public.bayi_duzeltme_talepleri (
  id          bigint generated by default as identity primary key,
  bayi_id     bigint not null references public.bayiler (id) on delete cascade,
  bdt_seri_no text not null,
  bdt_metin   text not null check (length(trim(bdt_metin)) > 0),
  bdt_tarih   date not null,
  bdt_durum   text not null default 'acik' check (bdt_durum in ('acik', 'cozuldu')),
  bdt_cozum   text,
  created_at  timestamptz not null default now()
);
create index bayi_duzeltme_talepleri_bayi_id_idx on public.bayi_duzeltme_talepleri (bayi_id);

