-- 14. Bayi dokümanları, duyurular, eğitim
-- ═════════════════════════════════════════════════════════════
create table public.bayi_dokumanlari (
  id          bigint generated by default as identity primary key,
  bd_kod      text unique,             -- demo / sabit dokümanların kısa adı ("e-kurulum")
  bd_baslik   text not null check (length(trim(bd_baslik)) > 0),
  bd_aciklama text not null default '',
  bd_kategori text not null check (bd_kategori in ('Ürün broşürleri', 'Teknik dokümanlar', 'Eğitim', 'Sözleşme ekleri', 'Pazarlama')),
  bd_tur      text not null check (bd_tur in ('pdf', 'gorsel', 'video')),
  bd_dosya_adi text not null,
  bd_mime     text,
  bd_boyut    bigint not null default 0 check (bd_boyut >= 0),
  bd_tarih    date not null default current_date,
  bd_hepsine  boolean not null default true,   -- false: yalnızca bayi_dokuman_hedefleri'ndeki bayiler
  bd_sure     text,                             -- eğitim: "12 dk"
  bd_demo     boolean not null default false,   -- dosyası örnek olarak üretilir
  bd_yol      text,                             -- Storage: bayi-dokumanlari/<yol>
  created_at  timestamptz not null default now()
);

create table public.bayi_dokuman_hedefleri (
  dokuman_id bigint not null references public.bayi_dokumanlari (id) on delete cascade,
  bayi_id    bigint not null references public.bayiler (id) on delete cascade,
  primary key (dokuman_id, bayi_id)
);
create index bayi_dokuman_hedefleri_bayi_id_idx on public.bayi_dokuman_hedefleri (bayi_id);

create table public.bayi_duyurulari (
  id          bigint generated by default as identity primary key,
  bdu_baslik  text not null check (length(trim(bdu_baslik)) > 0),
  bdu_metin   text not null,
  bdu_onem    text not null default 'normal' check (bdu_onem in ('normal', 'onemli')),
  bdu_tarih   timestamp not null,
  bdu_hepsine boolean not null default true,
  created_at  timestamptz not null default now()
);

create table public.bayi_duyuru_hedefleri (
  duyuru_id bigint not null references public.bayi_duyurulari (id) on delete cascade,
  bayi_id   bigint not null references public.bayiler (id) on delete cascade,
  primary key (duyuru_id, bayi_id)
);
create index bayi_duyuru_hedefleri_bayi_id_idx on public.bayi_duyuru_hedefleri (bayi_id);

create table public.bayi_duyuru_okumalari (
  duyuru_id  bigint not null references public.bayi_duyurulari (id) on delete cascade,
  bayi_id    bigint not null references public.bayiler (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (duyuru_id, bayi_id)
);
create index bayi_duyuru_okumalari_bayi_id_idx on public.bayi_duyuru_okumalari (bayi_id);

create table public.bayi_egitim_tamamlamalari (
  dokuman_id bigint not null references public.bayi_dokumanlari (id) on delete cascade,
  bayi_id    bigint not null references public.bayiler (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (dokuman_id, bayi_id)
);
create index bayi_egitim_tamamlamalari_bayi_id_idx on public.bayi_egitim_tamamlamalari (bayi_id);
