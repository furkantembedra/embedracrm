-- 13. Bayinin kendi lead'leri ve teklifleri (Embedra görmez)
-- ═════════════════════════════════════════════════════════════
create table public.bayi_leadleri (
  id                 bigint generated by default as identity primary key,
  bayi_id            bigint not null references public.bayiler (id) on delete cascade,
  bl_firma           text not null check (length(trim(bl_firma)) > 0),
  bl_yetkili         text not null default '',
  bl_telefon         text not null default '',
  bl_eposta          text not null default '',
  bl_sehir           text not null default '',
  bl_kaynak          text not null default '',
  bl_ilgi_model      text not null check (bl_ilgi_model in ('ONE', 'ONE Lite')),
  bl_ilgi_adet       integer not null default 1 check (bl_ilgi_adet > 0),
  bl_ilgi_plan       text not null default '' check (bl_ilgi_plan in ('', 'Basic', 'Pro', 'Pro+')),
  bl_tutar           numeric(14, 2),
  bl_asama           text not null default 'yeni' check (bl_asama in ('yeni', 'gorusuldu', 'demo', 'teklif', 'kazanildi', 'kaybedildi')),
  bl_kayip_nedeni    text,
  bl_sonraki_adim    text not null default '',
  bl_sonraki_tarih   date,
  bl_olusturma       date not null default current_date,
  bl_kapanis         date,
  bl_satilan_seriler text[] not null default '{}',
  created_at         timestamptz not null default now()
);
create index bayi_leadleri_bayi_id_idx on public.bayi_leadleri (bayi_id);

create table public.bayi_lead_notlari (
  id         bigint generated by default as identity primary key,
  lead_id    bigint not null references public.bayi_leadleri (id) on delete cascade,
  bln_zaman  timestamp not null,
  bln_metin  text not null,
  bln_sistem boolean not null default false
);
create index bayi_lead_notlari_lead_zaman_idx on public.bayi_lead_notlari (lead_id, bln_zaman);

create table public.bayi_lead_teklifleri (
  id                  bigint generated by default as identity primary key,
  lead_id             bigint not null references public.bayi_leadleri (id) on delete cascade,
  blt_no              text not null unique,   -- "DP-2026-014", revizyonda "DP-2026-014-v2"
  blt_gorunen_no      text not null,
  blt_versiyon        smallint not null default 1 check (blt_versiyon > 0),
  blt_iskonto         numeric(5, 2) not null default 0 check (blt_iskonto between 0 and 100),
  blt_kdv             numeric(4, 3) not null default 0 check (blt_kdv between 0 and 1),
  blt_gecerlilik      date not null,
  blt_odeme_sartlari  text not null default '',
  blt_teslim_sartlari text not null default '',
  blt_not             text not null default '',
  blt_durum           text not null default 'taslak' check (blt_durum in ('taslak', 'gonderildi', 'kabul', 'red', 'revize')),
  blt_olusturma       date not null default current_date,
  blt_gonderim        date,
  blt_sonuc           date,
  created_at          timestamptz not null default now()
);
create index bayi_lead_teklifleri_lead_idx on public.bayi_lead_teklifleri (lead_id, blt_versiyon);

create table public.bayi_lead_teklif_kalemleri (
  id               bigint generated by default as identity primary key,
  teklif_id        bigint not null references public.bayi_lead_teklifleri (id) on delete cascade,
  bltk_sira        smallint not null default 0,
  bltk_tur         text not null check (bltk_tur in ('cihaz', 'lisans', 'ozel')),
  bltk_model       text check (bltk_model in ('ONE', 'ONE Lite')),
  bltk_paket       text,
  bltk_aciklama    text,
  bltk_adet        integer not null check (bltk_adet > 0),
  bltk_birim_fiyat numeric(14, 2) not null,
  bltk_kdvli       boolean not null default true
);
create index bayi_lead_teklif_kalemleri_teklif_idx on public.bayi_lead_teklif_kalemleri (teklif_id, bltk_sira);

