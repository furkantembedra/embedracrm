do $$
declare r record; enbuyuk bigint;
begin
  for r in select c.relname t, a.attname k, pg_get_serial_sequence('public.' || quote_ident(c.relname), a.attname) s
           from pg_attribute a join pg_class c on c.oid = a.attrelid
           where c.relnamespace = 'public'::regnamespace and c.relkind = 'r' and a.attidentity <> '' loop
    execute format('select max(%I) from public.%I', r.k, r.t) into enbuyuk;
    if r.t = 'bayi_basvurulari' then
      enbuyuk := greatest(coalesce(enbuyuk, 0), coalesce((select max(id) from public.bayiler), 0));
    end if;
    if coalesce(enbuyuk, 0) > 0 then perform setval(r.s, enbuyuk); end if;
  end loop;
end $$;

